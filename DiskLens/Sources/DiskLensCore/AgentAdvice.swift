import Foundation

/// Shared decision support for every transport and analysis mode.
enum AgentAdvice {
    static let instructions = """
    Твоя задача — помочь принять решение об очистке, а не перечислить общие предостережения.
    Дай практическую рекомендацию на основании доступных сведений, даже если часть сведений отсутствует.
    Для каждого предложенного действия назови конкретный путь из данных, измеренный объём,
    обоснование и ожидаемое последствие: например, повторная загрузка кэша или потеря возможности перемонтажа.
    Различай факты замера, выводы по структуре и условия, которые ещё нужно проверить.
    Известный кэш и воспроизводимые результаты сборки обычно можно очищать после завершения работы
    соответствующего приложения; назови конкретное последствие. Имя папки само по себе не доказывает воспроизводимость.
    В рабочих проектах разделяй исходники, финальные результаты, промежуточные материалы и кэш.
    Папку проекта целиком сохраняй; проверяй, можно ли очистить отдельные вложенные объекты.
    Кадры, рендеры, экспорты и версии по дням могут быть промежуточными результатами, но не считай их
    дублями или воспроизводимыми без подтверждения. Дай условие: что сохранить и что подтвердить перед очисткой.
    Если решение зависит от неизвестного факта, сформулируй ветвление «если …, удалить …; иначе сохранить …»
