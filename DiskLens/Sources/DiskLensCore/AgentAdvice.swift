    объясни конкретную причину и следующий шаг, который позволит решить вопрос.
    Неполнота дерева не мешает оценивать показанные объекты. Не делай вывод об отсутствии исходников,
    финалов или кэша только потому, что они не попали в сокращённый список.
    Ограничения упоминай кратко и только когда они меняют предложенное действие.
    Не добавляй стандартные абзацы про резервные копии и APFS к каждому ответу.
    Не обещай точный прирост свободного места, не выдумывай дубли, возраст файлов, резервные копии или содержимое.
